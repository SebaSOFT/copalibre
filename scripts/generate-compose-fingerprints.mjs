#!/usr/bin/env node
// Writes apps/copalibre/src/released-compose-fingerprints.ts: the normalised SHA-256 of the
// docker-compose.yml, and the SHA-256 of the gateway Caddyfile, every stable release tag shipped
// (from 1.0.1 on), which `copalibre upgrade` compares an installation's files against. Run it
// after a release is tagged, so the next CLI recognises installations of that release:
//
//   node scripts/generate-compose-fingerprints.mjs
//
// The normalisation must match apps/copalibre/src/compose-fingerprint.ts; its test recomputes the
// fingerprint of each shipped file it can read and compares.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'apps', 'copalibre', 'src', 'released-compose-fingerprints.ts');

export function normalizeCompose(content) {
  return content
    .replace(/\r\n/g, '\n')
    .replace(/(ghcr\.io\/sebasoft\/copalibre(?:-web)?:)[A-Za-z0-9_.-]+/g, '$1<version>')
    .replace(/(\$\{COPALIBRE_VERSION:-)[^}]*(\})/g, '$1<version>$2')
    .replace(
      /^(\s*-\s*)(['"]?)(?:127\.0\.0\.1:)?(\d+:\d+)\2(\s*)$/gm,
      (_line, prefix, _quote, mapping) => `${prefix}${mapping}`,
    )
    .replace(/\n*$/, '\n');
}

function git(...args) {
  return execFileSync('git', args, {
    cwd: root,
    encoding: 'utf8',
    maxBuffer: 16 * 1024 * 1024,
    stdio: ['ignore', 'pipe', 'ignore'],
  });
}

function compareVersions(a, b) {
  const pa = a.split('.').map(Number);
  const pb = b.split('.').map(Number);
  for (let index = 0; index < 3; index += 1) {
    if (pa[index] !== pb[index]) return pa[index] - pb[index];
  }
  return 0;
}

const versions = git('tag', '--list', 'v*')
  .split('\n')
  .map((tag) => tag.trim().replace(/^v/, ''))
  .filter((version) => /^\d+\.\d+\.\d+$/.test(version))
  .filter((version) => compareVersions(version, '1.0.1') >= 0)
  .sort(compareVersions);

function show(version, path) {
  try {
    return git('show', `v${version}:${path}`);
  } catch {
    return undefined;
  }
}

const sha256 = (content) => createHash('sha256').update(content, 'utf8').digest('hex');

const composeEntries = versions.map(
  (version) =>
    `  '${version}': '${sha256(normalizeCompose(show(version, 'docker-compose.yml')))}',`,
);
const caddyEntries = versions.flatMap((version) => {
  const content = show(version, 'deploy/gateway/Caddyfile');
  return content ? [`  '${version}': '${sha256(content.replace(/\r\n/g, '\n'))}',`] : [];
});

writeFileSync(
  target,
  [
    '// Generated by scripts/generate-compose-fingerprints.mjs from the release tags; do not edit.',
    '',
    '/** The normalised SHA-256 of the docker-compose.yml each stable release shipped. */',
    'export const RELEASED_COMPOSE_FINGERPRINTS: Readonly<Record<string, string>> = {',
    ...composeEntries,
    '};',
    '',
    '/** The SHA-256 of the gateway Caddyfile each stable release shipped, where it shipped one. */',
    'export const RELEASED_GATEWAY_CADDYFILE_FINGERPRINTS: Readonly<Record<string, string>> = {',
    ...caddyEntries,
    '};',
    '',
  ].join('\n'),
);
process.stdout.write(`Wrote ${versions.length} release fingerprint(s) to ${target}\n`);
