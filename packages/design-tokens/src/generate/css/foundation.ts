/**
 * Under reduced motion every duration becomes zero.
 *
 * Overridden at the custom-property level rather than per component, so a
 * component added later inherits the behaviour instead of having to remember
 * it.
 */
export function reducedMotion(): string {
  return [
    '@media (prefers-reduced-motion: reduce) {',
    '  :root {',
    ...(['fast', 'base', 'slow', 'flash', 'pulse'] as const).map(
      (name) => `    --cl-motion-${name}: ${MOTION.instant};`,
    ),
    '  }',
    '',
    '  *, *::before, *::after {',
    '    animation-duration: 0s !important;',
    '    animation-iteration-count: 1 !important;',
    '    transition-duration: 0s !important;',
    '  }',
    '}',
  ].join('\n');
}

